def test_vercel_database_url_uses_postgres_without_opening_sqlite(tmp_path, monkeypatch):
    monkeypatch.setenv("VERCEL", "1")
    monkeypatch.delenv("DATABASE_URL", raising=False)

    class Connection:
        def __init__(self):
            self.statements = []
            self.committed = False

        def execute(self, query, parameters=()):
            self.statements.append((query, parameters))
            return self

        def commit(self):
            self.committed = True

        def close(self):
            pass

    connection = Connection()
    monkeypatch.setattr(
        app_module.psycopg,
        "connect",
        lambda database_url, **_kwargs: (
            connection if database_url == "postgresql://test" else pytest.fail()
        ),
    )
    monkeypatch.setattr(
        app_module.sqlite3,
        "connect",
        lambda *_args, **_kwargs: pytest.fail("Vercel attempted to open SQLite"),
    )

    create_app({
        "DATABASE": str(tmp_path / "read-only" / "app.db"),
        "DATABASE_URL": "postgresql://test",
        "UPLOAD_FOLDER": str(tmp_path / "uploads"),
    })

    assert connection.committed
    assert any("CREATE TABLE IF NOT EXISTS users" in query for query, _ in connection.statements)


